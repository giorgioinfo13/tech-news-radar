export type Language = 'it' | 'en'
export type MessageKey = keyof typeof italian
export type MessageValues = Record<string, string | number>
export type UiMessage = { messageKey: MessageKey; values?: MessageValues }

export function message(messageKey: MessageKey, values?: MessageValues): UiMessage {
  return { messageKey, values }
}

export function translate(
  input: MessageKey | UiMessage,
  language: Language,
  values?: MessageValues,
): string {
  const descriptor = typeof input === 'string' ? message(input, values) : input
  const template = language === 'en' ? descriptor.messageKey : italian[descriptor.messageKey]
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(descriptor.values?.[name] ?? placeholder),
  )
}
